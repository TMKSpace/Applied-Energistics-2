package net.neoforged.neoforge.data.event;

import java.nio.file.Path;
import java.util.Collection;
import java.util.List;
import java.util.concurrent.CompletableFuture;
import net.minecraft.core.HolderLookup;
import net.minecraft.data.DataGenerator;
import net.minecraft.data.DataProvider;
import net.minecraft.data.PackOutput;
import net.minecraft.data.tags.TagsProvider;
import net.minecraft.world.level.block.Block;
import net.neoforged.bus.api.Event;
import net.neoforged.fml.ModContainer;
import net.neoforged.fml.event.IModBusEvent;

/**
 * Gathers the providers used to generate data and resources.
 *
 * @see GatherDataEvent.Client
 * @see GatherDataEvent.Server
 */
public abstract sealed class GatherDataEvent extends Event implements IModBusEvent {
    private final GeneratorHandle generatorHandle;
    private final ModContainer modContainer;
    private final DatapackRegistrySets registries;
    private final PackGenerator defaultPackGenerator;
    private int packCounter = 0;

    /// SHIM: the default {@link PackOutput} has to be passed in, because vanilla {@link DataGenerator} does not
    /// expose the {@code PackOutput} it was created with.
    protected GatherDataEvent(ModContainer modContainer, DataGenerator dataGenerator, PackOutput defaultOutput,
            DatapackRegistrySets registries) {
        this.modContainer = modContainer;
        this.generatorHandle = new GeneratorHandle(dataGenerator, defaultOutput);
        this.registries = registries;
        this.defaultPackGenerator = new PackGenerator(this, defaultOutput, modContainer.getModId() + "-global");
    }

    public ModContainer getModContainer() {
        return this.modContainer;
    }

    public Collection<Path> getInputs() {
        return List.of();
    }

    /**
     * {@return the data generator}
     *
     * <p>SHIM: NeoForge patches {@code DataGenerator} with {@code #getPackOutput}. Since Minecraft cannot be patched
     * on Fabric, the shim returns a small handle that forwards to the vanilla generator and adds the missing method.
     */
    public GeneratorHandle getGenerator() {
        return this.generatorHandle;
    }

    /**
     * Forwarding wrapper around a vanilla {@link DataGenerator} that exposes the NeoForge-only {@code PackOutput}
     * accessor.
     */
    public static final class GeneratorHandle {
        private final DataGenerator delegate;
        private final PackOutput packOutput;

        private GeneratorHandle(DataGenerator delegate, PackOutput packOutput) {
            this.delegate = delegate;
            this.packOutput = packOutput;
        }

        public PackOutput getPackOutput() {
            return packOutput;
        }

        public DataGenerator getDelegate() {
            return delegate;
        }

        public DataGenerator.PackGenerator getVanillaPack(boolean includeDev) {
            return delegate.getVanillaPack(includeDev);
        }
    }

    public PackGenerator getDefaultPackGenerator() {
        return defaultPackGenerator;
    }

    public PackGenerator getPackGenerator(PackOutput output) {
        return new PackGenerator(this, output, this.modContainer.getModId() + "-pack[" + (packCounter++) + "]");
    }

    /**
     * {@return the world registries with all modded entries}
     */
    public CompletableFuture<HolderLookup.Provider> getWorldLookupProvider() {
        return this.registries.worldAndDimension();
    }

    /**
     * {@return the reloadable registries with all modded entries}
     */
    public CompletableFuture<HolderLookup.Provider> getReloadableLookupProvider() {
        return this.registries.reloadable();
    }

    /**
     * Shim note: there is no dev-mode flag in Fabric datagen, always {@code true}.
     */
    public boolean includeDev() {
        return true;
    }

    /**
     * Shim note: reports are not generated by the shim.
     */
    public boolean includeReports() {
        return false;
    }

    /**
     * Shim note: there is no validation pass in the shim.
     */
    public boolean validate() {
        return false;
    }

    public static final class Server extends GatherDataEvent {
        public Server(ModContainer modContainer, DataGenerator dataGenerator, PackOutput defaultOutput,
                DatapackRegistrySets registries) {
            super(modContainer, dataGenerator, defaultOutput, registries);
        }
    }

    public static final class Client extends GatherDataEvent {
        public Client(ModContainer modContainer, DataGenerator dataGenerator, PackOutput defaultOutput,
                DatapackRegistrySets registries) {
            super(modContainer, dataGenerator, defaultOutput, registries);
        }
    }

    public <T extends DataProvider> T addProvider(T provider) {
        return this.defaultPackGenerator.addProvider(provider);
    }

    public <T extends DataProvider> T createProvider(PackGenerator.DataProviderFromOutput<T> builder) {
        return this.defaultPackGenerator.createProvider(builder);
    }

    public <T extends DataProvider> T createProvider(PackGenerator.DataProviderFromOutputLookup<T> builder) {
        return this.defaultPackGenerator.createProvider(builder);
    }

    public void createBlockAndItemTags(PackGenerator.DataProviderFromOutputLookup<TagsProvider<Block>> blockTagsProvider,
            PackGenerator.ItemTagsProvider itemTagsProvider) {
        this.defaultPackGenerator.createBlockAndItemTags(blockTagsProvider, itemTagsProvider);
    }
}
